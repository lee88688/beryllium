/** Where extracted/archived book payloads live; injectable for tests. */
export interface EpubStorage {
  asarDir: string;
  /** Original PDFs; each book is `<booksDir>/<fileName>.pdf`. */
  booksDir: string;
  tempDir: string;
}

export function epubStorageFromEnv(): EpubStorage {
  const env = getEnv();
  return {
    asarDir: env.ASAR_DIR,
    booksDir: env.BOOKS_DIR,
    tempDir: env.TEMP_DIR,
  };
}

/** `<asarDir>/<name>.asar`. `name` is a uuid generated by this module. */
export function asarFileDir(name: string, storage: EpubStorage): string {
  return path.join(storage.asarDir, `${name}.asar`);
}

/** `<booksDir>/<name>.pdf`. */
export function pdfFileDir(name: string, storage: EpubStorage): string {
  return path.join(storage.booksDir, `${name}.pdf`);
}

/** Zip-bomb / memory guards, injectable so tests never depend on process env. */
export interface EpubLimits {
  /** Total uncompressed bytes one archive may expand to. */
  maxExtractedBytes: number;
  /** Largest single member allowed to be read into memory. */
  maxMemberBytes: number;
}

export function epubLimitsFromEnv(): EpubLimits {
  const env = getEnv();
  return {
    maxExtractedBytes: env.MAX_EXTRACTED_SIZE_MB * 1024 * 1024,
    maxMemberBytes: env.MAX_MEMBER_SIZE_MB * 1024 * 1024,
  };
}

/** Rounds a byte budget for the user-facing message. */
function megabytesOf(bytes: number): number {
  return Math.round(bytes / (1024 * 1024));
}

/**
 * Object.prototype members. `files["__proto__"]` in the ASAR index resolves to
 * `Object.prototype` instead of `undefined`, so a member named after one of
 * these turns a lookup into a 500; the route rejects them up front. (The
 * `__proto__` key must be computed, otherwise the literal would set the
 * prototype instead of adding the entry.)
 */
const FORBIDDEN_MEMBER_SEGMENTS: Record<string, boolean> = {
  ["__proto__"]: true,
  constructor: true,
  prototype: true,
};

/**
 * Characters that cannot occur in an archive member name: NTFS
 * alternate-data-stream (`:`) and Windows-reserved punctuation. Windows refuses
 * such paths anyway, so a book containing one is unusable.
 */
const INVALID_MEMBER_CHARACTERS = /[<>:"|?*]/;

/** C0 control bytes (NUL included) never appear in a usable member name. */
function hasControlCharacter(value: string): boolean {
  for (const character of value) {
    if ((character.codePointAt(0) ?? 0) < 0x20) return true;
  }
  return false;
}

/**
 * Canonical ASAR-relative member path, or `BAD_REQUEST`.
 *
 * Rejects absolute paths, `..`/`.` segments, empty segments and the
 * prototype-polluting names above; the returned value always uses `/` so an
 * archive written on Windows is readable from Linux and vice versa.
 */
export function normalizeMemberPath(filePath: string): string {
  const normalized = filePath.replaceAll("\\", "/").replace(/^\/+/, "");
  const segments = normalized.split("/");
  const invalid =
    normalized.length === 0 ||
    INVALID_MEMBER_CHARACTERS.test(normalized) ||
    hasControlCharacter(normalized) ||
    segments.some(
      (segment) =>
        segment === "" ||
        segment === "." ||
        segment === ".." ||
        Object.hasOwn(FORBIDDEN_MEMBER_SEGMENTS, segment),
    );
  if (invalid) {
    throw new RequestError("BAD_REQUEST", `无效的文件路径: ${filePath}`);
  }
  return segments.join("/");
}

/**
 * Extraction budget for one archive. The declared size of every entry is
 * checked up front (a 10 KB zip claiming 100 GB fails before anything is
 * written) and the bytes actually produced are counted too, so a header that
 * lies about its own size cannot get past it either.
 */
class ExtractBudget {
  #used = 0;

  constructor(private readonly limits: EpubLimits) {}

  reserve(declaredBytes: number): void {
    if (this.#used + declaredBytes > this.limits.maxExtractedBytes) {
      throw this.#overflow();
    }
  }

  account(writtenBytes: number): void {
    this.#used += writtenBytes;
    if (this.#used > this.limits.maxExtractedBytes) throw this.#overflow();
  }

  #overflow(): RequestError {
    return new RequestError(
      "BAD_REQUEST",
      `解压后文件超过 ${megabytesOf(this.limits.maxExtractedBytes)}MB 上限`,
    );
  }
}

const asarCache = new LRUCache<string, EasyAsar>({
  max: 500,
  allowStale: true,
  updateAgeOnGet: true,
  updateAgeOnHas: true,
});

/**
 * Archives whose index has been read. `EasyAsar.fetchIndex` has no memo of its
 * own (only `readFile` checks), so without this every call would re-read the
 * index; it also gives the size lookup below something to stand on.
 */
const indexedArchives = new WeakSet<EasyAsar>();

async function openArchive(
  asarFile: string,
  memberPath: string,
): Promise<EasyAsar> {
  const cached = asarCache.get(asarFile);
  const archive = cached ?? new EasyAsar(fsGetter(asarFile));
  if (!cached) {
    asarCache.set(asarFile, archive);
  }
  if (indexedArchives.has(archive)) return archive;

  try {
    await archive.fetchIndex();
  } catch (error) {
    // A missing/corrupt archive carries filesystem detail (absolute paths) in
    // its message; log it and answer with the same generic miss as a missing
    // member (B10). Evicting keeps the LRU from handing the broken instance out
    // again.
    console.error(`[readAsarFile] archive ${asarFile} is unreadable`, error);
    asarCache.delete(asarFile);
    throw new RequestError("NOT_FOUND", `书籍文件不可读: ${memberPath}`);
  }
  indexedArchives.add(archive);
  return archive;
}

/** Identity of one archive member, read from the index only. */
export interface AsarMemberStat {
  /** Byte offset of the member's data inside the ASAR payload. */
  offset: number;
  /** Declared uncompressed size in bytes. */
  size: number;
}

/** Subset of an ASAR index node the readers rely on. */
interface AsarIndexEntry {
  offset?: string | number;
  size?: number;
  files?: unknown;
}

/**
 * Resolves one index entry and enforces the shared "is a file" contract.
 * Every reader goes through this so a missing member, a directory entry and a
 * malformed index node map to the same status whichever path asks.
 */
function requireMemberEntry(
  archive: EasyAsar,
  filePath: string,
  normalized: string,
): AsarMemberStat {
  let entry: AsarIndexEntry;
  try {
    entry = archive.getFileIndex(normalized) as AsarIndexEntry;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      throw new RequestError(
        "NOT_FOUND",
        `archive file not found: ${filePath}`,
      );
    }
    throw error;
  }
  if (entry.files !== undefined) {
    throw new RequestError("BAD_REQUEST", `归档成员不是文件: ${filePath}`);
  }
  const offset = Number(entry.offset);
  if (
    entry.offset === undefined ||
    typeof entry.size !== "number" ||
    !Number.isFinite(offset)
  ) {
    throw new RequestError("NOT_FOUND", `archive file not found: ${filePath}`);
  }
  return { offset, size: entry.size };
}

/**
 * Reads one file out of a book's ASAR. Archives stay open in a process-wide LRU
 * (max 500, stale reads allowed) because a single reader session hammers it.
 *
 * A member larger than `limits.maxMemberBytes` answers `PAYLOAD_TOO_LARGE`
 * *before* it is buffered, so one huge entry in an otherwise acceptable book
 * cannot be turned into a memory spike.
 */
export async function readAsarFile(
  asarFile: string,
  filePath: string,
  limits: EpubLimits = epubLimitsFromEnv(),
): Promise<Buffer> {
  const normalized = normalizeMemberPath(filePath);
  const archive = await openArchive(asarFile, normalized);

  try {
    const entry = requireMemberEntry(archive, filePath, normalized);
    if (entry.size > limits.maxMemberBytes) {
      throw new RequestError(
        "PAYLOAD_TOO_LARGE",
        `文件超过 ${megabytesOf(limits.maxMemberBytes)}MB 上限`,
      );
    }
    // asar-async opens a stream with `end = offset - 1` for an empty member,
    // which Node rejects; an empty file is still a valid 200.
    if (entry.size === 0) return Buffer.alloc(0);
    return await archive.readFile(normalized);
  } catch (error) {
    // asar-async reports both a missing archive and a missing member as ENOENT;
    // the REST file route turns this into 404.
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      throw new RequestError(
        "NOT_FOUND",
        `archive file not found: ${filePath}`,
      );
    }
    if (isRequestError(error)) throw error;
    console.error(`[readAsarFile] failed to read ${normalized}`, error);
    throw new RequestError("NOT_FOUND", `archive file not found: ${filePath}`);
  }
}

/**
 * Looks up a member's index entry without touching its bytes. The member route
 * uses this to derive a strong ETag before deciding between 304 and a full
 * read. The size budget is applied here too, so a conditional request observes
 * exactly the status a plain GET would (413, never a 304).
 */
export async function statAsarMember(
  asarFile: string,
  filePath: string,
  limits: EpubLimits = epubLimitsFromEnv(),
): Promise<AsarMemberStat> {
  const normalized = normalizeMemberPath(filePath);
  const archive = await openArchive(asarFile, normalized);

  try {
    const entry = requireMemberEntry(archive, filePath, normalized);
    if (entry.size > limits.maxMemberBytes) {
      throw new RequestError(
        "PAYLOAD_TOO_LARGE",
        `文件超过 ${megabytesOf(limits.maxMemberBytes)}MB 上限`,
      );
    }
    return entry;
  } catch (error) {
    if (isRequestError(error)) throw error;
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      throw new RequestError(
        "NOT_FOUND",
        `archive file not found: ${filePath}`,
      );
    }
    console.error(`[statAsarMember] failed to read ${normalized}`, error);
    throw new RequestError("NOT_FOUND", `archive file not found: ${filePath}`);
  }
}

/**
 * Sizes of the requested members without reading a single byte of them.
 *
 * The reader needs these before a book can be built at all: foliate-js asks
 * for a section's size synchronously while assembling `.sections`
 * (`vendor/foliate-js/epub.js:991`) and uses them for the reading progress, so
 * they travel with the reader payload instead of costing a round trip per
 * chapter. Members the archive does not hold, and directory entries, are simply
 * omitted — a size is a hint, never a reason to fail a request.
 */
export async function readAsarMemberSizes(
  asarFile: string,
  paths: readonly string[],
): Promise<Map<string, number>> {
  const sizes = new Map<string, number>();
  const first = paths[0];
  if (first === undefined) return sizes;
  const archive = await openArchive(asarFile, first);

  for (const filePath of paths) {
    try {
      const normalized = normalizeMemberPath(filePath);
      sizes.set(
        filePath,
        requireMemberEntry(archive, filePath, normalized).size,
      );
    } catch (error) {
      // A missing/directory/malformed member is a hint we omit, not a failure.
      if (isRequestError(error)) continue;
      console.error(`[readAsarMemberSizes] failed on ${filePath}`, error);
    }
  }
  return sizes;
}

/** Passes chunks through while charging them to the archive's extraction budget. */
function countBytes(budget: ExtractBudget): Transform {
  return new Transform({
    transform(chunk: Buffer, _encoding, callback) {
      try {
        budget.account(chunk.byteLength);
        callback(null, chunk);
      } catch (error) {
        callback(error as Error);
      }
    },
  });
}

/**
 * Declared (central directory / local header) uncompressed size of an entry.
 *
 * Read through a runtime guard because `@types/unzipper` omits the field that
 * unzip-stream's `vars` does carry; an absent or non-numeric value simply means
 * "unknown", and the byte counter then does all the work.
 */
function declaredUncompressedSize(entry: unzipper.Entry): number {
  const vars: unknown = entry.vars;
  if (vars === null || typeof vars !== "object") return 0;
  if (!("uncompressedSize" in vars)) return 0;
  return typeof vars.uncompressedSize === "number" ? vars.uncompressedSize : 0;
}

/** Extracts one archive entry under `outputDir`, rejecting zip-slip paths. */
async function extractEntry(
  entry: unzipper.Entry,
  outputDir: string,
  budget: ExtractBudget,
): Promise<void> {
  const target = safeJoin(outputDir, entry.path);
  budget.reserve(declaredUncompressedSize(entry));
  if (entry.type === "Directory") {
    await mkdirp(target);
    await entry.autodrain().promise();
    return;
  }
  await mkdirp(path.dirname(target));
  await pipeline(entry, countBytes(budget), createWriteStream(target));
}

/**
 * Streams every archive entry to disk. unzipper emits entries as events (its
 * Parse stream is not async-iterable), so entries are written as they arrive
 * and the first failure is rethrown once the stream is drained.
 *
 * The first failing entry aborts the parse immediately: a zip bomb must not be
 * worth draining to the end.
 */
async function extractArchive(
  fileStream: Readable,
  outputDir: string,
  budget: ExtractBudget,
): Promise<void> {
  const parser = fileStream.pipe(unzipper.Parse({ verbose: false }));
  const writes: Promise<void>[] = [];
  let failure: unknown;
  // Once the upload is aborted, unzipper can still emit an entry from bytes it
  // had already buffered. Starting a write for it would recreate the temp
  // directory after `convertEpubToAsar` removed it (flaky on Linux CI).
  let aborted = false;
  // Split the two failure sources: an upload that stops mid-stream (transport)
  // keeps its own error, while bytes the parser cannot read at all are a bad
  // archive and become a 400 (D3) instead of the generic 500.
  let sourceError: unknown;
  let archiveError: unknown;

  const drained = new Promise<void>((resolve, reject) => {
    parser.on("entry", (entry: unzipper.Entry) => {
      if (aborted) {
        // Discard instead of writing: no directory is recreated, and the
        // parser is not held up waiting for a consumer that will never read.
        entry.resume();
        return;
      }
      writes.push(
        extractEntry(entry, outputDir, budget).catch((error: unknown) => {
          failure ??= error;
          aborted = true;
          parser.destroy();
          fileStream.destroy();
        }),
      );
    });
    parser.on("error", (error: unknown) => {
      archiveError ??= error;
      reject(error);
    });
    parser.on("close", resolve);
    // pipe() does not forward source errors: an aborted upload must reject here
    // too, otherwise this promise would never settle.
    fileStream.on("error", (error: unknown) => {
      sourceError ??= error;
      reject(error);
    });
  });

  let pendingError: unknown;
  try {
    await drained;
  } catch (error) {
    aborted = true;
    parser.destroy();
    fileStream.destroy();
    if (sourceError !== undefined) {
      pendingError = sourceError;
    } else if (archiveError !== undefined) {
      console.error(
        "[extractArchive] not a readable zip archive",
        archiveError,
      );
      pendingError = new RequestError(
        "BAD_REQUEST",
        "上传的文件不是有效的 ZIP/EPUB 归档",
      );
    } else {
      pendingError = error;
    }
  }

  // An entry write can still be in flight when the stream dies. Let it settle
  // before the caller removes the temp directory, otherwise the write recreates
  // files inside it after the cleanup and they stay behind (Linux timing makes
  // this visible; the aborted-upload test pins it).
  await Promise.all(writes);

  if (pendingError !== undefined) throw pendingError;
  if (failure !== undefined) throw failure;
}

/**
 * Streams an EPUB into `temp/<uuid>` and repacks it as `asar/<name>.asar`.
 * Extraction is entry-by-entry (no whole-file buffering) and every
 * entry path goes through `safeJoin`, which rejects zip-slip.
 *
 * The temp directory is removed on both success and failure, and a packaging
 * failure removes its half-written ASAR too (B13), so neither directory can
 * accumulate leftovers.
 */
export async function convertEpubToAsar(
  fileStream: Readable,
  destFileName: string,
  storage: EpubStorage = epubStorageFromEnv(),
  limits: EpubLimits = epubLimitsFromEnv(),
): Promise<string> {
  const outputDir = path.join(storage.tempDir, uuidv1());
  const asarPath = asarFileDir(destFileName, storage);
  await mkdirp(outputDir);

  try {
    await extractArchive(fileStream, outputDir, new ExtractBudget(limits));
    await mkdirp(storage.asarDir);
    try {
      await asar.createPackage(outputDir, asarPath);
    } catch (error) {
      console.error(`[convertEpubToAsar] packaging ${asarPath} failed`, error);
      await fsp.rm(asarPath, { force: true });
      throw error;
    }
    return asarPath;
  } finally {
    await rimraf(outputDir);
  }
}

export async function deleteEpubFile(
  name: string,
  storage: EpubStorage = epubStorageFromEnv(),
): Promise<void> {
  // `force` keeps this idempotent: deleting a book whose archive is already
  // gone (or whose upload failed half-way) must not throw.
  try {
    await fsp.rm(asarFileDir(name, storage), { force: true });
  } catch (error) {
    // The row is already gone by the time cleanup runs (see `deleteUser`), so
    // an unremovable file must not look like a failed deletion: log the real
    // reason (absolute path and all) and report a generic failure.
    console.error(`[deleteEpubFile] could not remove ${name}.asar`, error);
    throw new RequestError("INTERNAL", "书籍文件删除失败，请稍后重试");
  }
}

export async function deletePdfFile(
  name: string,
  storage: EpubStorage = epubStorageFromEnv(),
): Promise<void> {
  try {
    await fsp.rm(pdfFileDir(name, storage), { force: true });
  } catch (error) {
    console.error(`[deletePdfFile] could not remove ${name}.pdf`, error);
    throw new RequestError("INTERNAL", "书籍文件删除失败，请稍后重试");
  }
}

/** Format-aware cleanup used by book/user deletion. */
export async function deleteBookFile(
  book: Pick<BookSelect, "fileName" | "format">,
  storage: EpubStorage = epubStorageFromEnv(),
): Promise<void> {
  if (book.format === "pdf") {
    await deletePdfFile(book.fileName, storage);
    return;
  }
  await deleteEpubFile(book.fileName, storage);
}

/**
 * Moves an already validated upload from `TEMP_DIR` into `BOOKS_DIR`.
 *
 * A plain rename is atomic when both directories are on the same filesystem.
 * When they are not (`EXDEV`), copy to a sibling temp name inside `BOOKS_DIR`
 * first and rename that into place: readers can never observe a half-written
 * `<uuid>.pdf`, and a failure leaves only a removable `.tmp` file.
 */
async function movePdfIntoStorage(
  tempPath: string,
  destination: string,
  storage: EpubStorage,
): Promise<void> {
  await mkdirp(storage.booksDir);
  try {
    await fsp.rename(tempPath, destination);
    return;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EXDEV") throw error;
  }

  const staging = `${destination}.${uuidv4()}.tmp`;
  try {
    await fsp.copyFile(tempPath, staging);
    await fsp.rename(staging, destination);
    await fsp.rm(tempPath, { force: true });
  } catch (error) {
    await fsp.rm(staging, { force: true });
    throw error;
  }
}

/**
 * Persists a PDF upload. `pdfPackage` is the browser-parsed description or the
 * explicit degraded package when parsing was skipped; `content` is NOT NULL,
 * so there is no other shape.
 */
export async function savePdfFile(
  db: Database,
  userId: number,
  tempPath: string,
  originalName: string,
  pdfPackage: PdfPackage,
  storage: EpubStorage = epubStorageFromEnv(),
): Promise<BookSelect> {
  const fileName = uuidv4();
  const destination = pdfFileDir(fileName, storage);
  const title =
    pdfPackage.metadata.title.trim() || titleFromFilename(originalName);
  const content: PdfPackage = {
    ...pdfPackage,
    metadata: {
      ...pdfPackage.metadata,
      title,
      author: pdfPackage.metadata.author.trim(),
      description: pdfPackage.metadata.description.trim(),
    },
  };

  try {
    await movePdfIntoStorage(tempPath, destination, storage);
  } catch (error) {
    console.error(`[savePdfFile] could not store ${destination}`, error);
    throw new RequestError("INTERNAL", "保存书籍文件失败，请稍后重试");
  }

  try {
    return db
      .insert(Book)
      .values({
        fileName,
        userId,
        format: "pdf",
        contentPath: "",
        current: "",
        cover: "",
        content,
        title: content.metadata.title,
        author: content.metadata.author,
        description: content.metadata.description,
      })
      .returning()
      .get();
  } catch (error) {
    await fsp.rm(destination, { force: true });
    console.error("[savePdfFile] could not store the book row", error);
    throw new RequestError("INTERNAL", "保存书籍信息失败，请稍后重试");
  }
}

/**
 * Full upload pipeline: unzip → asar → read `container.xml`/OPF → insert row.
 * On any failure after packing, the freshly created ASAR is removed so the
 * data directory cannot accumulate orphans; the temp directory is
 * always removed by `convertEpubToAsar`.
 */
export async function saveEpubFile(
  db: Database,
  userId: number,
  fileStream: Readable,
  storage: EpubStorage = epubStorageFromEnv(),
  limits: EpubLimits = epubLimitsFromEnv(),
): Promise<BookSelect> {
  const fileName = uuidv4();
  const asarPath = await convertEpubToAsar(
    fileStream,
    fileName,
    storage,
    limits,
  );

  try {
    const contentPath = await parseContainerPath(
      (await readAsarFile(asarPath, "META-INF/container.xml", limits)).toString(
        "utf8",
      ),
    );
    const content = await parseOpf(
      (await readAsarFile(asarPath, contentPath, limits)).toString("utf8"),
    );

    try {
      return db
        .insert(Book)
        .values({
          fileName,
          userId,
          format: "epub",
          contentPath,
          current: "",
          content,
          ...fillInBaseInfo(content, contentPath),
        })
        .returning()
        .get();
    } catch (error) {
      // SQLite text (table/column names, constraint ids) is internal detail;
      // log it and answer with a message the UI may show (B10).
      console.error("[saveEpubFile] could not store the book row", error);
      throw new RequestError("INTERNAL", "保存书籍信息失败，请稍后重试");
    }
  } catch (error) {
    await fsp.rm(asarPath, { force: true });
    // A missing container.xml/OPF means the upload is not a usable EPUB; report
    // it as a bad request rather than the internal NOT_FOUND of the ASAR read.
    if (isRequestError(error) && error.code === "NOT_FOUND") {
      throw new RequestError(
        "BAD_REQUEST",
        "上传的文件不是有效的 EPUB：缺少或无法读取 container.xml / OPF",
      );
    }
    throw error;
  }
}
